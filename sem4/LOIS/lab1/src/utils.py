class FormulaError(Exception):
    """Пользовательское исключение для ошибок синтаксиса и логики формулы."""
    pass

def die(msg: str) -> None:
    """
    Выбрасывает исключение с сообщением об ошибке.
    Это позволяет перехватить ошибку на уровне меню и не закрывать программу.
    """
    raise FormulaError(msg)